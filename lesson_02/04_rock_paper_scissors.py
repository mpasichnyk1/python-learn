"""Урок 2, додаткова гра: камінь, ножиці, папір (один раунд)."""

import random

options = ["камінь", "ножиці", "папір"]
computer = random.choice(options)  # Випадково обираємо елемент зі списку.

print("=== КАМІНЬ, НОЖИЦІ, ПАПІР ===")
player = input("Твій вибір (камінь/ножиці/папір): ").strip().lower()

if player not in options:
    print("Такого варіанта немає. Запусти гру ще раз!")
else:
    print(f"Комп'ютер обрав: {computer}")

    if player == computer:
        print("Нічия!")
    elif (
        (player == "камінь" and computer == "ножиці")
        or (player == "ножиці" and computer == "папір")
        or (player == "папір" and computer == "камінь")
    ):
        print("Ти переміг(ла)!")
    else:
        print("Цього разу переміг комп'ютер!")

