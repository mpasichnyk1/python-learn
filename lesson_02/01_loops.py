"""Урок 2, крок 1. Цикли: повторюємо дії без копіювання коду."""

# range(1, 6) створює числа 1, 2, 3, 4, 5 (6 НЕ включає).
print("=== Зворотний відлік ===")
for number in range(5, 0, -1):
    print(number)
print("Старт!")

# Список (list) зберігає кілька значень в одному місці.
print("\n=== Улюблені страви ===")
foods = ["піца", "суші", "борщ"]
for food in foods:
    print(f"Сьогодні скуштуємо: {food}")

# while повторює код, ДОКИ умова правдива.
print("\n=== Три кроки ===")
steps_left = 3
while steps_left > 0:
    print(f"Залишилося кроків: {steps_left}")
    steps_left = steps_left - 1  # Без зміни умови цикл може тривати вічно.

# break завершує цикл достроково.
print("\n=== Знайдемо число 3 ===")
for number in range(1, 10):
    if number == 3:
        print("Знайшли! Зупиняємо цикл.")
        break
    print("Ще не 3:", number)

# continue пропускає решту ПОТОЧНОГО повторення циклу.
print("\n=== Лише непарні числа ===")
for number in range(1, 6):
    if number % 2 == 0:
        continue
    print(number)

