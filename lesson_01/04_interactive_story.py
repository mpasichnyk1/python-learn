"""Урок 1, крок 4. Мініпроєкт: пригода з кількома кінцівками."""

print("=== ПРИГОДА: ТАЄМНИЙ ПОРТАЛ ===")
hero = input("Як звати твого героя? ").strip()

# Привітаємо героя. Якщо людина натисне Enter, дамо їй ім'я.
if hero == "":
    hero = "Мандрівник"

print(f"{hero}, ти знайшов(ла) портал у незнайомий світ!")
path = input("Куди підеш: ліс чи замок? ").strip().lower()

if path == "ліс":
    print("Між деревами з'являється загадковий дракон.")
    action = input("Що робитимеш: говорити чи тікати? ").strip().lower()

    if action == "говорити":
        print(f"Дракон усміхається: 'Вітаю, {hero}! Ти знайшов(ла) нового друга.'")
    elif action == "тікати":
        print("Ти встигаєш втекти й знаходиш скриню із золотом!")
    else:
        print("Поки ти вагаєшся, дракон спокійно засинає.")

elif path == "замок":
    print("Ти бачиш двоє дверей: червоні та сині.")
    door = input("Які відчиниш: червоні чи сині? ").strip().lower()

    if door == "червоні":
        print("За дверима — кімната, повна піци! Перемога!")
    elif door == "сині":
        print("За дверима — портал додому та чарівна книжка Python.")
    else:
        print("Ти знайшов(ла) прихований третій прохід!")

else:
    print("Портал зачиняється. Та це лише початок наступної пригоди...")

print("=== КІНЕЦЬ ІСТОРІЇ ===")

