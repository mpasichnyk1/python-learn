"""Урок 1, крок 2. input() і прості обчислення."""

# input() зупиняє програму й чекає, поки людина введе текст.
name = input("Як тебе звати? ")
print(f"Радий знайомству, {name}!")

# УВАГА: input() завжди повертає текст (str).
# int(...) перетворює текст із цілим числом на int.
age_text = input("Скільки тобі повних років? ")
age = int(age_text)
print(f"Через 5 років тобі буде {age + 5}.")

# float(...) потрібен для дробових чисел, наприклад 12.50.
# Уведи дріб через крапку, НЕ через кому.
ticket_price = float(input("Ціна одного квитка (наприклад 12.5): "))
ticket_count = int(input("Скільки квитків купуємо? "))

# * — множення. Значення в total зберігаємо для подальшої роботи.
total = ticket_price * ticket_count
print(f"До сплати: {total:.2f} грн")  # .2f — показати 2 знаки після крапки.

# Інші математичні дії:
print("Ділення 7 / 2 =", 7 / 2)
print("Ціле ділення 7 // 2 =", 7 // 2)
print("Остача 7 % 2 =", 7 % 2)

