"""Урок 1, крок 3. Програма може ухвалювати рішення."""

# if — «якщо», elif — «інакше якщо», else — «в усіх інших випадках».
# Відступ у 4 пробіли показує, що команди належать до умови.

temperature = int(input("Яка температура надворі (ціле число)? "))

if temperature < 0:
    print("Мороз! Одягни теплу куртку.")
elif temperature < 15:
    print("Прохолодно. Візьми светр.")
else:
    print("Досить тепло для прогулянки!")

# == порівнює значення, а = записує значення в змінну.
# .strip() забирає зайві пробіли на початку/в кінці.
# .lower() перетворює великі літери на малі.
answer = input("Тобі подобаються комп'ютерні ігри? (так/ні): ").strip().lower()

if answer == "так":
    print("Тоді можемо створити власну гру на Python!")
elif answer == "ні":
    print("Можемо зробити програму про музику, спорт або фільми!")
else:
    print("Цікава відповідь! Наступного разу спробуй 'так' або 'ні'.")

